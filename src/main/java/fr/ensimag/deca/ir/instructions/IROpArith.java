package fr.ensimag.deca.ir.instructions;

/**
 * Enumeration of arithmetic operations supported in the IR.
 *
 * @author gl25
 * @date 01/01/2026
 */
public enum IROpArith {
    /** Addition operation */
    ADD,
    /** Subtraction operation */
    SUB,
    /** Multiplication operation */
    MUL,
    /** Division operation */
    DIV,
    /** Modulo operation */
    MOD
}

